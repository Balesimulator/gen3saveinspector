    private Gen3SpeciesData() {}

    static boolean hasBaseStats(int speciesId) {
        return baseStat(speciesId, STAT_HP) != 0;
    }

    static int baseStat(int speciesId, int stat) {
        long value = data(speciesId);
        int shift;
        switch (stat) {
            case STAT_HP:  shift = 0; break;
            case STAT_ATK: shift = 8; break;
            case STAT_DEF: shift = 16; break;
            case STAT_SPE: shift = 24; break;
            case STAT_SPA: shift = 32; break;
            case STAT_SPD: shift = 40; break;
            default: throw new IllegalArgumentException("Unknown stat: " + stat);
        }
        return (int) ((value >>> shift) & 0xFFL);
    }

    static int genderRatio(int speciesId) {
        return (int) ((data(speciesId) >>> 48) & 0xFFL);
    }

    static int growthRate(int speciesId) {
        return (int) ((data(speciesId) >>> 56) & 0xFFL);
    }

    private static long data(int speciesId) {
        return speciesId >= 0 && speciesId < DATA.length ? DATA[speciesId] : DATA[0];
    }
